package com.doppsy.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UuidGenerator;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Represents a Doppsy healthcare provider — doctor, veterinarian, dietician, etc.
 *
 * <p>Maps to the {@code providers} table in PostgreSQL.</p>
 */
@Entity
@Table(name = "providers")
@Data
@NoArgsConstructor
@AllArgsConstructor
public class Provider {

    /** Surrogate primary key; UUID v4 auto-generated by the database. */
    @Id
    @UuidGenerator
    @Column(name = "provider_id", updatable = false, nullable = false)
    private UUID providerId;

    /** Legal full name of the healthcare provider. */
    @Column(name = "full_name", length = 255, nullable = false)
    private String fullName;

    /**
     * Clinical specialty of the provider.
     * Stored as the enum name string (e.g., "Allopathy").
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "specialty", length = 100, nullable = false)
    private Specialty specialty;

    /** Name of the clinic or hospital where the provider practises. */
    @Column(name = "clinic_name", length = 255)
    private String clinicName;

    /** Human-readable address or geo-coordinate string. */
    @Column(name = "location", length = 500)
    private String location;

    /**
     * Monetisation tier for the provider's Doppsy subscription.
     * Stored as the enum name string (e.g., "FREE").
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "monthly_subscription_tier", length = 20, nullable = false)
    private SubscriptionTier monthlySubscriptionTier = SubscriptionTier.FREE;

    /** {@code true} once the provider's credentials have been verified by the Doppsy team. */
    @Column(name = "is_verified", nullable = false)
    private Boolean isVerified = false;

    /** UTC timestamp of provider onboarding; set automatically on insert. */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    // ------------------------------------------------------------------
    // Nested enums
    // ------------------------------------------------------------------

    /** Supported clinical specialties on the Doppsy platform. */
    public enum Specialty {
        Allopathy,
        Ayurveda,
        Homeopathy,
        Veterinary,
        Dietician,
        Dentistry,
        Dermatology,
        Physiotherapy,
        Other
    }

    /** Provider subscription tiers controlling platform features and commission. */
    public enum SubscriptionTier {
        /** Basic listing, limited slots. */
        FREE,
        /** Priority listing and analytics dashboard. */
        BASIC,
        /** Zero-commission, advanced analytics, verified badge. */
        PREMIUM
    }
}
