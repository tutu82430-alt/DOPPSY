package com.doppsy.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UuidGenerator;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Represents a single bookable appointment slot — the core transaction entity
 * in the Doppsy zero-wait-time booking engine.
 *
 * <p>Lifecycle: {@code AVAILABLE → BOOKED → COMPLETED | CANCELLED}</p>
 *
 * <p>Maps to the {@code appointments} table in PostgreSQL.</p>
 */
@Entity
@Table(
    name = "appointments",
    indexes = {
        @Index(name = "idx_appt_user_id",            columnList = "user_id"),
        @Index(name = "idx_appt_provider_id",         columnList = "provider_id"),
        @Index(name = "idx_appt_status",              columnList = "status"),
        @Index(name = "idx_appt_timestamp",           columnList = "appointment_timestamp"),
        // Critical composite index for the zero-wait booking engine
        @Index(name = "idx_appt_provider_status_ts",  columnList = "provider_id, status, appointment_timestamp")
    }
)
@Data
@NoArgsConstructor
@AllArgsConstructor
public class Appointment {

    /** Surrogate primary key; UUID v4 auto-generated by the database. */
    @Id
    @UuidGenerator
    @Column(name = "appointment_id", updatable = false, nullable = false)
    private UUID appointmentId;

    /**
     * The patient who booked this slot.
     * {@code NULL} while the slot is in {@code AVAILABLE} status (unbooked).
     *
     * <p>FK → users(user_id) ON DELETE SET NULL</p>
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = true)
    @JoinColumn(
        name = "user_id",
        referencedColumnName = "user_id",
        foreignKey = @ForeignKey(name = "fk_appointment_user")
    )
    private User user;

    /**
     * The healthcare provider who owns this slot.
     * Always required; cannot be {@code NULL}.
     *
     * <p>FK → providers(provider_id) ON DELETE RESTRICT</p>
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
        name = "provider_id",
        referencedColumnName = "provider_id",
        nullable = false,
        foreignKey = @ForeignKey(name = "fk_appointment_provider")
    )
    private Provider provider;

    /** Scheduled UTC date and time of the appointment. */
    @Column(name = "appointment_timestamp", nullable = false)
    private LocalDateTime appointmentTimestamp;

    /**
     * Current lifecycle state of the slot.
     * Stored as the enum name string (e.g., "AVAILABLE").
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", length = 20, nullable = false)
    private AppointmentStatus status = AppointmentStatus.AVAILABLE;

    /**
     * Fee charged to the patient in INR (or platform currency).
     * Precision of 10 digits with 2 decimal places.
     */
    @Column(name = "booking_fee", precision = 10, scale = 2)
    private BigDecimal bookingFee;

    /** Razorpay order ID generated during the booking deposit flow. */
    @Column(name = "razorpay_order_id", length = 50)
    private String razorpayOrderId;

    /** Razorpay payment ID captured after successful payment verification. */
    @Column(name = "razorpay_payment_id", length = 50)
    private String razorpayPaymentId;

    /** UTC timestamp when this slot was first created; set automatically on insert. */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    // ------------------------------------------------------------------
    // Nested enum
    // ------------------------------------------------------------------

    /**
     * Lifecycle states for an appointment slot.
     *
     * <pre>
     * AVAILABLE ──► BOOKED ──► COMPLETED
     *                  │
     *                  └──────► CANCELLED
     * </pre>
     */
    public enum AppointmentStatus {
        /** Slot is open and can be claimed by any patient. */
        AVAILABLE,
        /** Slot has been reserved, pending ₹200 booking deposit via Razorpay. */
        PENDING_PAYMENT,
        /** Slot has been reserved and payment verified. */
        BOOKED,
        /** Appointment was attended and concluded. */
        COMPLETED,
        /** Appointment was cancelled before attending. */
        CANCELLED,
        /** Patient did not arrive for the scheduled appointment. */
        NO_SHOW,
        /** Slot was blocked out by doctor/clinic and cannot be booked. */
        BLOCKED
    }
}
