package com.doppsy.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.UuidGenerator;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Represents a patient health document record (prescription, lab report, etc.).
 * Binary files are stored externally in AWS S3; only the URL is persisted here.
 *
 * <p>Maps to the {@code health_records} table in PostgreSQL.</p>
 */
@Entity
@Table(
    name = "health_records",
    indexes = {
        @Index(name = "idx_hr_user_id",     columnList = "user_id"),
        @Index(name = "idx_hr_provider_id", columnList = "provider_id"),
        @Index(name = "idx_hr_record_type", columnList = "record_type"),
        @Index(name = "idx_hr_uploaded_at", columnList = "uploaded_at")
    }
)
@Data
@NoArgsConstructor
@AllArgsConstructor
public class HealthRecord {

    /** Surrogate primary key; UUID v4 auto-generated by the database. */
    @Id
    @UuidGenerator
    @Column(name = "record_id", updatable = false, nullable = false)
    private UUID recordId;

    /**
     * The patient who owns this health record.
     * Deletion of the owning user cascades to delete all their records.
     *
     * <p>FK → users(user_id) ON DELETE CASCADE</p>
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
        name = "user_id",
        referencedColumnName = "user_id",
        nullable = false,
        foreignKey = @ForeignKey(name = "fk_health_record_user")
    )
    private User user;

    /**
     * The healthcare provider who issued this record.
     * Nullable — records from external labs may not have a Doppsy provider.
     *
     * <p>FK → providers(provider_id) ON DELETE SET NULL</p>
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = true)
    @JoinColumn(
        name = "provider_id",
        referencedColumnName = "provider_id",
        foreignKey = @ForeignKey(name = "fk_health_record_provider")
    )
    private Provider provider;

    /** Pre-signed or permanent AWS S3 / CDN URL pointing to the document. */
    @Column(name = "document_url", length = 2048, nullable = false)
    private String documentUrl;

    /**
     * Category of the health document.
     * Stored as the enum name string (e.g., "PRESCRIPTION").
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "record_type", length = 50, nullable = false)
    private RecordType recordType;

    /** UTC timestamp when the document was uploaded; set automatically on insert. */
    @Column(name = "uploaded_at", nullable = false, updatable = false)
    private LocalDateTime uploadedAt = LocalDateTime.now();

    // ------------------------------------------------------------------
    // Nested enum
    // ------------------------------------------------------------------

    /** Supported categories of patient health documents. */
    public enum RecordType {
        PRESCRIPTION,
        LAB_REPORT,
        IMAGING,
        VACCINATION,
        OTHER
    }
}
