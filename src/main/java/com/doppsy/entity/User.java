package com.doppsy.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UuidGenerator;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Represents a Doppsy platform user — either a Patient or an Admin.
 * Authentication is mobile-first; {@code mobileNumber} serves as the login identifier.
 *
 * <p>Maps to the {@code users} table in PostgreSQL.</p>
 */
@Entity
@Table(
    name = "users",
    uniqueConstraints = @UniqueConstraint(name = "uk_users_mobile", columnNames = "mobile_number")
)
@Data
@NoArgsConstructor
@AllArgsConstructor
public class User {

    /** Surrogate primary key; UUID v4 auto-generated by the database. */
    @Id
    @UuidGenerator
    @Column(name = "user_id", updatable = false, nullable = false)
    private UUID userId;

    /** E.164-format mobile number; the primary login identifier. */
    @Column(name = "mobile_number", length = 15, nullable = false, unique = true)
    private String mobileNumber;

    /** Display name of the user. */
    @Column(name = "full_name", length = 255, nullable = false)
    private String fullName;

    /** Age in years. Must be between 1 and 149. */
    @Column(name = "age")
    private Integer age;

    /**
     * Access-control role of the user.
     * Stored as the enum name string (e.g., "PATIENT").
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "role", length = 20, nullable = false)
    private UserRole role = UserRole.PATIENT;

    /** UTC timestamp of account creation; set automatically on insert. */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    // ------------------------------------------------------------------
    // Nested enum — kept in the same file for cohesion
    // ------------------------------------------------------------------

    /** Allowed roles for a Doppsy platform user. */
    public enum UserRole {
        /** Regular patient booking appointments. */
        PATIENT,
        /** Platform operator with elevated privileges. */
        ADMIN
    }
}
