package com.doppsy.controller;

import com.doppsy.service.WhatsAppWebhookService;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

/**
 * Controller providing the Meta WhatsApp Business Cloud API webhook endpoints:
 * <ul>
 *   <li>{@code GET /api/v1/whatsapp/webhook} — Meta Webhook subscription verification</li>
 *   <li>{@code POST /api/v1/whatsapp/webhook} — Incoming messages receiver and concierge processor</li>
 * </ul>
 */
@Slf4j
@RestController
@RequestMapping("/api/v1/whatsapp")
public class WhatsAppWebhookController {

    private final String expectedVerifyToken;
    private final WhatsAppWebhookService webhookService;

    private final com.doppsy.jobs.AppointmentReminderJob reminderJob;

    public WhatsAppWebhookController(
        @Value("${doppsy.whatsapp.verify-token}") String verifyToken,
        WhatsAppWebhookService webhookService,
        com.doppsy.jobs.AppointmentReminderJob reminderJob
    ) {
        this.expectedVerifyToken = verifyToken;
        this.webhookService = webhookService;
        this.reminderJob = reminderJob;
    }

    // -----------------------------------------------------------------------
    // GET /api/v1/whatsapp/webhook — Meta Verification Endpoint
    // -----------------------------------------------------------------------

    /**
     * Meta's mandatory webhook verification handshake.
     * When configuring the webhook URL in the Meta App Dashboard, Meta calls this
     * endpoint with {@code hub.mode}, {@code hub.verify_token}, and {@code hub.challenge}.
     *
     * <p>If {@code hub.verify_token} matches our configured secret, we return
     * {@code hub.challenge} with HTTP 200.</p>
     *
     * @param mode        should equal "subscribe"
     * @param challenge   random integer/token string generated by Meta
     * @param verifyToken secret token configured in Meta dashboard & application.yml
     * @return HTTP 200 with the plain challenge string on success, or HTTP 403 on mismatch
     */
    @GetMapping(value = "/webhook", produces = MediaType.TEXT_PLAIN_VALUE)
    public ResponseEntity<String> verifyWebhook(
        @RequestParam(value = "hub.mode", required = false) String mode,
        @RequestParam(value = "hub.challenge", required = false) String challenge,
        @RequestParam(value = "hub.verify_token", required = false) String verifyToken
    ) {
        log.info("[WHATSAPP WEBHOOK VERIFY] Handshake request: mode={}, token={}", mode, verifyToken);

        if ("subscribe".equals(mode) && expectedVerifyToken.equals(verifyToken)) {
            log.info("[WHATSAPP WEBHOOK VERIFY] Handshake successful. Returning challenge: {}", challenge);
            return ResponseEntity.ok(challenge);
        }

        log.warn("[WHATSAPP WEBHOOK VERIFY] Verification failed. Expected token: '{}', Received: '{}'",
            expectedVerifyToken, verifyToken);
        return ResponseEntity.status(HttpStatus.FORBIDDEN).body("Verification token mismatch");
    }

    // -----------------------------------------------------------------------
    // POST /api/v1/whatsapp/webhook — Inbound Message Receiver
    // -----------------------------------------------------------------------

    /**
     * Receives incoming WhatsApp messages from patients (e.g. "CANCEL" or general queries).
     * Dispatches the payload to {@link WhatsAppWebhookService} for conversational handling.
     *
     * @param rawPayload JSON body sent by Meta (or test client)
     * @return HTTP 200 OK acknowledgment ("EVENT_RECEIVED")
     */
    @PostMapping(value = "/webhook", consumes = MediaType.APPLICATION_JSON_VALUE)
    public ResponseEntity<String> handleIncomingMessage(@RequestBody String rawPayload) {
        log.info("[WHATSAPP WEBHOOK] Received message payload from Meta");
        webhookService.processWebhookPayload(rawPayload);
        return ResponseEntity.ok("EVENT_RECEIVED");
    }

    // -----------------------------------------------------------------------
    // POST /api/v1/whatsapp/test-reminder — Test Trigger Endpoint
    // -----------------------------------------------------------------------

    /**
     * Triggers the 24-hour reminder job on-demand for testing.
     *
     * @param hours hours into the future to scan (default 24)
     * @return summary map
     */
    @PostMapping("/test-reminder")
    public ResponseEntity<java.util.Map<String, Object>> testReminder(
        @RequestParam(value = "hours", defaultValue = "24") int hours
    ) {
        int sent = reminderJob.dispatchRemindersForWindow(hours);
        return ResponseEntity.ok(java.util.Map.of(
            "status", "SUCCESS",
            "hoursForward", hours,
            "remindersSent", sent
        ));
    }
}
